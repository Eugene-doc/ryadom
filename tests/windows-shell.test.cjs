'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');

test('Windows shell uses WebView2 identity and embedded SDK', () => {
 const window = read('windows/ChatWindow.cs');
 const launcher = read('windows/Launcher.cs');
 const build = read('scripts/build-windows.cjs');
 const identity = read('windows/DeviceIdentity.cs');
 const activation = read('windows/SingleInstanceActivation.cs');
 const loopback = read('windows/LoopbackActivation.cs');
 assert.match(window, /WebView2Bootstrap/);
 assert.match(activation, /NamedPipeServerStream/);
 assert.match(activation, /NamedPipeClientStream/);
 assert.match(activation, /AllowSetForegroundWindow/);
 assert.match(loopback, /TcpListener/);
 assert.match(loopback, /IPAddress\.Loopback/);
 assert.match(loopback, /AllowSetForegroundWindow/);
 assert.match(loopback, /activate-endpoint\./);
 assert.match(launcher, /SingleInstanceActivation/);
 assert.match(launcher, /ActivationRouter/);
 assert.match(launcher, /RequestOpenChat/);
 assert.doesNotMatch(launcher, /Рядом уже запущен/);
 assert.match(window, /ShowAndActivate/);
 assert.match(build, /SingleInstanceActivation\.cs/);
 assert.match(build, /LoopbackActivation\.cs/);
 assert.match(identity, /device-id/);
 assert.match(identity, /device-token/);
 assert.match(identity, /d1-/);
 assert.match(launcher, /RYADOM_DEVICE_ID/);
 assert.match(launcher, /RYADOM_DEVICE_TOKEN/);
 assert.match(build, /DeviceIdentity\.cs/);
 assert.match(window, /SetLoaderDllFolderPath/);
 assert.match(window, /Downloads.*Рядом|Рядом.*Downloads/s);
 assert.match(window, /Guid\.NewGuid/);
 assert.match(window, /UserDataFolder/);
 assert.match(window, /scriptsReady/);
 assert.doesNotMatch(window, /Text = "Открыть загрузки"/);
 assert.match(window, /OpenDownloads/);
 assert.match(window, /WebMessageReceived/);
 assert.match(window, /window\.ryadom=/);
 assert.match(window, /deviceId:/);
 assert.match(window, /deviceToken:/);
 assert.match(launcher, /Ryadom\.Chat/);
 assert.match(launcher, /SetCurrentProcessExplicitAppUserModelID/);
 assert.match(launcher, /new ChatWindow/);
 assert.match(launcher, /Создать ярлык/);
 assert.match(build, /WebView2\.Core\.dll/);
 assert.match(build, /WebView2Loader\.dll/);
 assert.doesNotMatch(launcher, /--app=\\"\s*\+url/);
});
